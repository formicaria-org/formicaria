#!/bin/sh
# Write the manual's assistant chapter, `docs/src/user/assistant.md`, from the Myrme this build links.
# **The chapter is written in Myrme** (`docs/manual/assistant.md`, its contract part 3a) and
# formicaria keeps no copy (`decisions.md#agent`, 2026-10-19): the file here is generated and
# gitignored, so the book in the app, in every archive and on the website describes the assistant
# that ships. Run by `ci/docs.sh` and by `ci/checks.sh` before it checks links into the manual.
set -eu
root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
src=$(sh "$root/ci/myrme-src.sh")
chapter="$src/docs/manual/assistant.md"
[ -f "$chapter" ] || { echo "myrme-manual: $chapter missing — the pinned Myrme predates contract 1.4" >&2; exit 1; }
tag=$(sed -n 's/.*formicaria-org\/myrme\.git", tag = "\([^"]*\)".*/\1/p' "$root/crates/fm-serve/Cargo.toml" | head -1)
{
    printf '<!-- GENERATED by ci/myrme-manual.sh from Myrme %s, docs/manual/assistant.md — do not edit.\n' "$tag"
    printf '     Edit it in https://github.com/formicaria-org/myrme, then move the pin. -->\n'
    # Myrme's own header comment (what the file is, for a reader there) is dropped for this one.
    awk 'NR == 1 && /^<!--/ { skip = 1 } skip { if (/-->$/) skip = 0; next } { print }' "$chapter"
} > "$root/docs/src/user/assistant.md"
