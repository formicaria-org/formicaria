/// The per-second stream, summarised: what it has, never the values (those stay in the file).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Stream {
    pub records: usize,
    pub with_hr: usize,
    pub with_position: usize,
    pub with_altitude: usize,
    pub first: Option<i64>,
    pub last: Option<i64>,
}

/// Everything the import reads from one file.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct FitFile {
    pub file_id: Option<FileId>,
    /// Whether a `file_creator` message is present (the watch's own files carry one).
    pub has_creator: bool,
    /// The watch's offset from UTC at the end of the activity, in seconds: `activity.local_timestamp`
    /// minus `activity.timestamp`. `None` when the file does not say, or says something no clock
    /// on Earth reads (beyond ±14 h).
    pub local_offset_s: Option<i64>,
    /// `activity.timestamp`, Unix seconds UTC.
    pub activity_end: Option<i64>,
    pub sessions: Vec<Session>,
    pub laps: Vec<Lap>,
    pub lengths: Vec<Length>,
    pub sets: Vec<Set>,
    pub steps: Vec<WorkoutStep>,
    /// A workout file's `workout` message.
    pub workout: Option<WorkoutInfo>,
    pub stream: Stream,
    /// Messages the crate's profile does not name, counted and otherwise left alone.
    pub unknown_messages: usize,
}

// ── the frame: header, sizes, checksums ─────────────────────────────────────────────────────────

const CRC_TABLE: [u16; 16] = [
    0x0000, 0xCC01, 0xD801, 0x1400, 0xF001, 0x3C00, 0x2800, 0xE401, 0xA001, 0x6C00, 0x7800, 0xB401,
    0x5000, 0x9C01, 0x8801, 0x4400,
];

/// The FIT protocol's CRC-16 over `bytes`, from zero.
pub fn crc16(bytes: &[u8]) -> u16 {
    bytes.iter().fold(0u16, |crc, &b| {
        let mut crc = crc;
        let mut tmp = CRC_TABLE[(crc & 0xF) as usize];
        crc = (crc >> 4) & 0x0FFF;
        crc = crc ^ tmp ^ CRC_TABLE[(b & 0xF) as usize];
        tmp = CRC_TABLE[(crc & 0xF) as usize];
        crc = (crc >> 4) & 0x0FFF;
        crc ^ tmp ^ CRC_TABLE[((b >> 4) & 0xF) as usize]
    })
}

/// Check every FIT file in `bytes` (a file may be several, one after another): header size, the
/// `.FIT` signature, the header's own checksum when it has one, that the data the header promises
/// is all there, and the file's checksum. **Nothing is decoded before this passes.**
pub fn check_frame(bytes: &[u8]) -> Result<(), FitError> {
    if bytes.len() > MAX_BYTES {
        return Err(FitError::NotFit(format!(
            "it is {} MB, far larger than any activity file",
            bytes.len() / 1_000_000
        )));
    }
    let mut pos = 0usize;
    while pos < bytes.len() {
        let rest = &bytes[pos..];
        let first = pos == 0;
        let header = rest[0] as usize;
        if header != 12 && header != 14 {
            return Err(if first {
                FitError::NotFit("it does not start like a FIT file".into())
            } else {
                FitError::Damaged("it has bytes after its end that are not another file".into())
            });
        }
        if rest.len() < header {
            return Err(FitError::Damaged("it is cut short inside its header".into()));
        }
        if &rest[8..12] != b".FIT" {
            return Err(if first {
                FitError::NotFit("it does not carry the FIT signature".into())
            } else {
                FitError::Damaged("it has bytes after its end that are not another file".into())
            });
        }
        if header == 14 {
            let stored = u16::from_le_bytes([rest[12], rest[13]]);
            if stored != 0 && stored != crc16(&rest[..12]) {
                return Err(FitError::Damaged("its header checksum does not match".into()));
            }
        }
        let data = u32::from_le_bytes([rest[4], rest[5], rest[6], rest[7]]) as usize;
        let end = header.saturating_add(data).saturating_add(2);
        if rest.len() < end {
            return Err(FitError::Damaged(format!(
                "it is cut short: its header promises {} bytes and {} are there",
                end,
                rest.len()
            )));
        }
        let stored = u16::from_le_bytes([rest[end - 2], rest[end - 1]]);
        if stored != crc16(&rest[..end - 2]) {
            return Err(FitError::Damaged("its checksum does not match its contents".into()));
        }
        pos += end;
    }
    if bytes.is_empty() {
        return Err(FitError::NotFit("it is empty".into()));
    }
    Ok(())
}

// ── decoding ─────────────────────────────────────────────────────────────────────────────────────

/// Read one FIT file. A damaged file is refused ([`check_frame`]); a well-formed one is decoded by
/// `rustyfit` and reduced to the records the import needs.
pub fn decode(bytes: &[u8]) -> Result<FitFile, FitError> {
    check_frame(bytes)?;
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| decode_checked(bytes))) {
        Ok(r) => r,
        Err(_) => Err(FitError::Unreadable("the decoder could not read it".into())),
    }
}

fn decode_checked(bytes: &[u8]) -> Result<FitFile, FitError> {
    let mut dec = rustyfit::Decoder::new();
    let mut reader: &[u8] = bytes;
    let mut out = FitFile::default();
    // A file may be several, one after another (`check_frame` has checked each).
    loop {
        let fit = match dec.decode(&mut reader) {
            Ok(Some(fit)) => fit,
            Ok(None) => break,
            Err(e) => return Err(FitError::Unreadable(format!("it could not be read ({e:?})"))),
        };
        for m in &fit.messages {
            read_message(m, &mut out);
        }
        if reader.is_empty() {
            break;
        }
    }
    Ok(out)
}

/// A message number the profile names (`Display` writes `MesgNum(n)` for one it does not).
fn named(num: typedef::MesgNum) -> bool {
    !num.to_string().contains('(')
}

fn read_message(m: &Message, out: &mut FitFile) {
    match m.num.0 {
        mesg::FILE_ID => {
            let f = mesgdef::FileId::from(m);
            out.file_id = Some(FileId {
                file_type: name(f.r#type),
                manufacturer: name(f.manufacturer),
                product: (f.product != u16::MAX).then(|| f.product.to_string()),
                serial: (f.serial_number != 0).then_some(f.serial_number),
                time_created: time(f.time_created),
                number: (f.number != u16::MAX).then_some(u32::from(f.number)),
            });
        }
        mesg::FILE_CREATOR => out.has_creator = true,
        mesg::ACTIVITY => {
            let a = mesgdef::Activity::from(m);
            out.activity_end = time(a.timestamp);
            // **The raw count, never a zone** (module header).
            let local = a.local_timestamp.0;
            if let (true, Some(end)) = (local != u32::MAX && local >= 0x1000_0000, out.activity_end)
            {
                let offset = i64::from(local) - (end - FIT_EPOCH);
                if offset.abs() <= 14 * 3600 {
                    out.local_offset_s = Some(offset);
                }
            }
        }
        mesg::SESSION => {
            let s = mesgdef::Session::from(m);
            out.sessions.push(Session {
                sport: name(s.sport),
                sub_sport: name(s.sub_sport),
                start: time(s.start_time),
                elapsed_s: u32v(s.total_elapsed_time).map(|v| v / 1000.0),
                timer_s: u32v(s.total_timer_time).map(|v| v / 1000.0),
                distance_m: u32v(s.total_distance).map(|v| v / 100.0),
                ascent_m: u16v(s.total_ascent),
                descent_m: u16v(s.total_descent),
                hr_avg: u8v(s.avg_heart_rate),
                hr_max: u8v(s.max_heart_rate),
                // Field 18: for a run the profile calls it `avg_running_cadence`, strides a minute.
                cadence_avg: u8v(s.avg_cadence),
                fractional_cadence: u8v(s.avg_fractional_cadence).map(|v| v / 128.0),
                calories: u16v(s.total_calories),
                training_effect: u8v(s.total_training_effect).map(|v| v / 10.0),
                anaerobic_effect: u8v(s.total_anaerobic_training_effect).map(|v| v / 10.0),
                // "multiplied 10x" (the profile's comment); scale 1, so the raw count.
                workout_rpe: u8v(s.workout_rpe),
                pool_length_m: u16v(s.pool_length).map(|v| v / 100.0),
                active_lengths: (s.num_active_lengths != u16::MAX)
                    .then_some(u32::from(s.num_active_lengths)),
            });
        }
        mesg::LAP => {
            let l = mesgdef::Lap::from(m);
            out.laps.push(Lap {
                start: time(l.start_time),
                timer_s: u32v(l.total_timer_time).map(|v| v / 1000.0),
                elapsed_s: u32v(l.total_elapsed_time).map(|v| v / 1000.0),
                distance_m: u32v(l.total_distance).map(|v| v / 100.0),
                hr_avg: u8v(l.avg_heart_rate),
                hr_max: u8v(l.max_heart_rate),
                speed_avg: u32v(l.enhanced_avg_speed)
                    .or_else(|| u16v(l.avg_speed))
                    .map(|v| v / 1000.0),
                wkt_step_index: (l.wkt_step_index.0 != u16::MAX)
                    .then_some(u32::from(l.wkt_step_index.0)),
            });
        }
        mesg::LENGTH => {
            let l = mesgdef::Length::from(m);
            out.lengths.push(Length {
                start: time(l.start_time),
                timer_s: u32v(l.total_timer_time).map(|v| v / 1000.0),
                strokes: (l.total_strokes != u16::MAX).then_some(u32::from(l.total_strokes)),
                stroke: name(l.swim_stroke),
                active: l.length_type != typedef::LengthType::IDLE,
                cadence: u8v(l.avg_swimming_cadence),
            });
        }
        mesg::SET => {
            let x = mesgdef::Set::from(m);
            let category = x.category.first().copied().and_then(name);
            let subtype = x.category_subtype.first().copied().filter(|n| *n != u16::MAX);
            let exercise =
                category.as_deref().zip(subtype).and_then(|(c, n)| exercise_name(c, i64::from(n)));
            out.sets.push(Set {
                start: time(x.start_time).or_else(|| time(x.timestamp)),
                duration_s: u32v(x.duration).map(|v| v / 1000.0),
                reps: (x.repetitions != u16::MAX).then_some(u32::from(x.repetitions)),
                weight_kg: u16v(x.weight).map(|v| v / 16.0).filter(|w| *w > 0.0),
                active: x.set_type != typedef::SetType::REST,
                category,
                exercise,
            });
        }
        mesg::WORKOUT_STEP => {
            let w = mesgdef::WorkoutStep::from(m);
            let value = u32v(w.duration_value);
            out.steps.push(WorkoutStep {
                index: (w.message_index.0 != u16::MAX).then_some(u32::from(w.message_index.0)),
                name: Some(w.wkt_step_name.to_string()).filter(|n| !n.is_empty()),
                intensity: name(w.intensity),
                // `duration_value` is `duration_time` (ms) or `duration_distance` (cm) by its type.
                duration_s: value
                    .filter(|_| w.duration_type == typedef::WktStepDuration::TIME)
                    .map(|v| v / 1000.0),
                distance_m: value
                    .filter(|_| w.duration_type == typedef::WktStepDuration::DISTANCE)
                    .map(|v| v / 100.0),
                duration_type: name(w.duration_type),
                duration_count: (w.duration_value != u32::MAX).then_some(w.duration_value),
                target_type: name(w.target_type),
                target_value: (w.target_value != u32::MAX).then_some(w.target_value),
                target_low: (w.custom_target_value_low != u32::MAX)
                    .then_some(w.custom_target_value_low),
                target_high: (w.custom_target_value_high != u32::MAX)
                    .then_some(w.custom_target_value_high),
                notes: Some(w.notes.to_string()).filter(|n| !n.is_empty()),
                weight_kg: u16v(w.exercise_weight).map(|v| v / 100.0),
            });
        }
        mesg::WORKOUT => {
            let w = mesgdef::Workout::from(m);
            out.workout = Some(WorkoutInfo {
                name: Some(w.wkt_name.to_string()).filter(|n| !n.is_empty()),
                sport: name(w.sport),
                steps: (w.num_valid_steps != u16::MAX).then_some(u32::from(w.num_valid_steps)),
            });
        }
        mesg::RECORD => {
            let r = mesgdef::Record::from(m);
            let s = &mut out.stream;
            s.records += 1;
            if r.heart_rate != u8::MAX {
                s.with_hr += 1;
            }
            if r.position_lat != i32::MAX && r.position_long != i32::MAX {
                s.with_position += 1;
            }
            if r.enhanced_altitude != u32::MAX || r.altitude != u16::MAX {
                s.with_altitude += 1;
            }
            if let Some(t) = time(r.timestamp) {
                s.first = Some(s.first.map_or(t, |x| x.min(t)));
                s.last = Some(s.last.map_or(t, |x| x.max(t)));
            }
        }
        _ if !named(m.num) => out.unknown_messages += 1,
        _ => {}
    }
}

/// The profile's name for a value (`running`), or `None` for an invalid one; a value the profile
/// does not name is kept as its number.
fn name<T: std::fmt::Display>(v: T) -> Option<String> {
    let s = v.to_string();
    match s.split_once('(') {
        // `Sport(255)`: invalid, or a number with no name.
        Some((_, n)) => {
            let n = n.trim_end_matches(')');
            (n != "255" && n != "65535" && n != "4294967295").then(|| n.to_string())
        }
        None => Some(s).filter(|s| !s.is_empty() && s != "invalid"),
    }
}

/// A UTC time as Unix seconds; `None` for the invalid value or a device-relative count.
fn time(t: typedef::DateTime) -> Option<i64> {
    (t.0 != u32::MAX && t.0 >= 0x1000_0000).then(|| i64::from(t.0) + FIT_EPOCH)
}

fn u8v(v: u8) -> Option<f64> {
    (v != u8::MAX).then_some(f64::from(v))
}
fn u16v(v: u16) -> Option<f64> {
    (v != u16::MAX).then_some(f64::from(v))
}
fn u32v(v: u32) -> Option<f64> {
    (v != u32::MAX).then_some(f64::from(v))
}

