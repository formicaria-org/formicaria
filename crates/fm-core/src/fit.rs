//! Reading a watch's activity file (FIT) — bytes in, plain records out.
//!
//! `decisions.md` 2026-11-20, *Watch data enters fm as files another app wrote* and *Reading and
//! writing FIT: open crates, a provenance note*. This module is the decoder half of that: it takes
//! the bytes of one file and returns what the import needs — the file's identity, its sessions,
//! laps, swim lengths, strength sets, a summary of the per-second stream, and the watch's own
//! offset from UTC. It has **no `Store`, no network and no paths**; whoever read the file hands the
//! bytes over, and whoever writes notes takes the records away (`fm_app::watch`).
//!
//! # Provenance
//!
//! - **Decoder:** the `rustyfit` crate, version 0.11.2 (BSD-3-Clause; its repository is named on
//!   the provenance page below — this file names no address at all, `ci/checks.sh`). Its message
//!   and field numbers, names, types and the scales of its `_scaled` readers come from **that
//!   crate's generated profile** (FIT profile 21.221, generated by the crate from the FIT SDK's
//!   `Profile.xlsx`). fm carries no copy of the profile of its own.
//! - **Why not `fitparser`**, which the decision named for reading: it brings `chrono`, which the
//!   advisory database now lists as unmaintained (RUSTSEC-2026-0543, no safe upgrade), so `pixi run
//!   deny` refuses it. `rustyfit` is the decision's other crate (the writer); it reads as well, has
//!   no dependency but `embedded-io`, and returns raw values with no time-zone conversion at all.
//! - **What fm wrote itself, from the FIT protocol's published description:** the frame check
//!   below (header size, the `.FIT` signature, the data size and the two CRCs, with the CRC-16
//!   table of the protocol), the few scales applied to raw values here (each beside its field), and
//!   the message numbers this file names ([`mesg`]): fm checks a file before the crate sees it, so
//!   a damaged file is refused and named rather than half-read.
//! - **Licence:** fm relies on the FIT Protocol License's §1 grant to use the FIT protocol in
//!   software the licensee creates. §2(c), §2(d) and §2(f) were read; the residual legal question is
//!   accepted, not settled (`decisions.md` 2026-11-20). The same note is in
//!   `docs/src/dev/fit-provenance.md`.
//!
//! # Time
//!
//! Every time is returned as **Unix seconds, UTC** (`FIT_EPOCH` + the file's count). The watch's
//! own local time (`activity.local_timestamp`) is read as the raw count it is and never put on this
//! computer's zone, so the watch's day cannot depend on where the file is read.
//! [`FitFile::local_offset_s`] is the watch's offset at the end of the activity — the only source
//! for the day a session belongs to (`fm_app::watch`).
//!
//! # Never a panic
//!
//! A file is whatever was on a folder. The frame check refuses a damaged one first, and the
//! decoding runs under `catch_unwind` as well, so that an unforeseen panic inside the crate becomes
//! a refusal with the file's name rather than a dead command (tested over seeded random and
//! mutated inputs: `fit_tests.rs`, T2).

use rustyfit::profile::mesgdef;
use rustyfit::profile::typedef;
use rustyfit::proto::Message;

/// 1989-12-31T00:00:00Z, the FIT protocol's zero, in Unix seconds.
pub const FIT_EPOCH: i64 = 631_065_600;

/// A watch's activity file is a few megabytes; anything past this is not one.
pub const MAX_BYTES: usize = 64 * 1024 * 1024;

/// The global message numbers this module reads (from the protocol's description; the crate's
/// profile names them the same).
pub mod mesg {
    pub const FILE_ID: u16 = 0;
    pub const SESSION: u16 = 18;
    pub const LAP: u16 = 19;
    pub const RECORD: u16 = 20;
    pub const WORKOUT: u16 = 26;
    pub const WORKOUT_STEP: u16 = 27;
    pub const ACTIVITY: u16 = 34;
    pub const FILE_CREATOR: u16 = 49;
    pub const LENGTH: u16 = 101;
    pub const SET: u16 = 225;
    /// `activity.local_timestamp` — the watch's local time, read raw (see the module header).
    pub const ACTIVITY_LOCAL_TIMESTAMP: u8 = 5;
    /// The timestamp field every message may carry.
    pub const TIMESTAMP: u8 = 253;
}

/// Why a file was not read. Each is one sentence a person can act on.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FitError {
    /// Not a FIT file at all (no header, no `.FIT` signature).
    NotFit(String),
    /// A FIT file, damaged or cut short: the sizes or a checksum do not agree.
    Damaged(String),
    /// Read by the frame check, but the decoder could not make sense of it.
    Unreadable(String),
}

impl std::fmt::Display for FitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            FitError::NotFit(s) | FitError::Damaged(s) | FitError::Unreadable(s) => f.write_str(s),
        }
    }
}

impl std::error::Error for FitError {}

/// `file_id`: what the file says it is and who made it. The serial number is here because the
/// identity needs it; the caller must never write it into a note in clear (`fm_app::watch` keys it
/// with a salted HMAC — the plan's P1.2).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct FileId {
    /// `activity`, `workout`, `monitoring_a`, … — the crate's name, or the number as text.
    pub file_type: Option<String>,
    pub manufacturer: Option<String>,
    pub product: Option<String>,
    pub serial: Option<u32>,
    /// Unix seconds, UTC.
    pub time_created: Option<i64>,
    pub number: Option<u32>,
}

impl FileId {
    /// The identity tuple of the plan's P1.2 — type, manufacturer, product, serial, time created —
    /// as one line of text, for the caller to key. `None` when the file says none of it.
    pub fn identity(&self) -> Option<String> {
        if self.serial.is_none() && self.time_created.is_none() {
            return None;
        }
        let o = |s: &Option<String>| s.clone().unwrap_or_default();
        Some(format!(
            "{}|{}|{}|{}|{}|{}",
            o(&self.file_type),
            o(&self.manufacturer),
            o(&self.product),
            self.serial.map(|n| n.to_string()).unwrap_or_default(),
            self.time_created.map(|n| n.to_string()).unwrap_or_default(),
            self.number.map(|n| n.to_string()).unwrap_or_default(),
        ))
    }
}

